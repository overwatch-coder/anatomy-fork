/**
 * Returns the organ with all text fields localized. Everything non-textual
 * (id, model, icon, accent, hotspot coordinates, colours) stays English-source.
 */
export function localizeOrgan(organ: Organ, lang: "en" | "ru"): Organ {
  if (lang !== "ru") return organ;
  const ru = organsRu[organ.id];
  if (!ru) return organ;
  const ruById = new Map(ru.hotspots.map((hotspot) => [hotspot.id, hotspot]));
  return {
    ...organ,
    genitive: ru.genitive,
    name: ru.name,
    system: ru.system,
    description: ru.description,
    poetic: ru.poetic,
    size: ru.size,
    weight: ru.weight,
    location: ru.location,
    function: ru.function,
    dailyFact: ru.dailyFact,
    medical: ru.medical,
    bloodSupply: ru.bloodSupply,
    funFact: ru.funFact,
    tissue: ru.tissue,
    comparison: ru.comparison,
    conditions: ru.conditions,
    hotspots: organ.hotspots.map((hotspot) => {
      const translated = ruById.get(hotspot.id);
      return translated ? { ...hotspot, label: translated.label, detail: translated.detail } : hotspot;
    }),
  };
}
